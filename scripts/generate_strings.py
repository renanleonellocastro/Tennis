#!/usr/bin/env python3
"""Generate the text tables of the app from the six strings.xml resource files.

The app reads its text from a table keyed by language code instead of the
compiled string resources. Connect IQ picks a compiled resource by the
system locale and cannot switch it at runtime, while a table can be looked
up (and later switched) by code. The base "eng" strings.xml is the
reference; all six files are kept in sync by scripts/check_resources.py.

Each table is a JSON resource (resources/texts/<code>.json, listed in
resources/texts/texts.xml) and source/generated/Strings.mc only says which
resource belongs to which code. A resource takes memory on the watch only
while it is loaded, so one language is in memory instead of six: tables
written as Monkey C code cost about 13 kB more on a watch with 124 kB.

Run: python3 scripts/generate_strings.py
"""

import json
import os
import xml.etree.ElementTree as ET

# Language code and its resource folder. "eng" is the base (default) folder.
LANGUAGES = [
    ("eng", "resources"),
    ("por", "resources-por"),
    ("spa", "resources-spa"),
    ("fre", "resources-fre"),
    ("deu", "resources-deu"),
    ("ita", "resources-ita"),
]

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT_PATH = os.path.join("source", "generated", "Strings.mc")
TEXTS_FOLDER = os.path.join("resources", "texts")
INDEX_PATH = os.path.join(TEXTS_FOLDER, "texts.xml")


def read_strings(folder):
    """Return an ordered {id: value} dict from a folder's strings.xml.

    ElementTree turns XML entities (such as &amp;) back into plain characters.
    """
    path = os.path.join(REPO_ROOT, folder, "strings", "strings.xml")
    root = ET.parse(path).getroot()
    return {node.get("id"): node.text or "" for node in root.findall("string")}


BASE_CODE = "eng"

HEADER_LINES = [
    "// GENERATED by scripts/generate_strings.py. DO NOT EDIT.",
    "//",
    "// Runtime i18n table. Connect IQ selects compiled string",
    "// resources by system locale and cannot switch them at runtime,",
    "// so translations are chosen here by language code. The texts",
    "// of each language are a JSON resource (resources/texts), which",
    "// takes memory only while it is loaded: a plain list, where the",
    "// place of a text is the number of its key in the Str module.",
    "import Toybox.Lang;",
    "import Toybox.WatchUi;",
    "",
]

MODULE_OPENING_LINES = [
    "",
    "module I18n {",
]

TABLE_OPENING_LINES = [
    "",
    "    // Reads the list of texts of ONE code, so only the chosen",
    "    // language is allocated. An unknown code gives eng.",
    "    function table(code as Lang.String) as Lang.Array<Lang.String> {",
]

TABLE_CLOSING_LINES = [
    "        return WatchUi.loadResource(id) as Lang.Array<Lang.String>;",
    "    }",
    "}",
    "",
]


def language_codes():
    return [code for code, _ in LANGUAGES]


def resource_id(code):
    return "Texts" + code.capitalize()


def constant_lines(codes):
    codes_literal = ", ".join('"%s"' % code for code in codes)
    return ["    const CODES = [%s];" % codes_literal]


def translated_entries(tables, code):
    """The text of every base key in base order, the eng one when a translation lacks it."""
    return [tables[code].get(key, value) for key, value in tables[BASE_CODE].items()]


def key_lines(keys):
    """One number per key, in base order: the place of its text in every table."""
    lines = ["// The keys of the texts. A key is a number, which takes far less", "// memory than its name.", "module Str {"]
    lines += ["    const %s = %d;" % (key, index) for index, key in enumerate(keys)]
    return lines + ["}"]


def choice_lines(codes):
    """eng is the resource the lookup starts from; every other code replaces it."""
    lines = ["        var id = Rez.JsonData.%s;" % resource_id(BASE_CODE)]
    for code in codes:
        if code != BASE_CODE:
            lines.append('        if (code.equals("%s")) { id = Rez.JsonData.%s; }' % (code, resource_id(code)))
    return lines


def render_module(keys):
    codes = language_codes()
    lines = HEADER_LINES + key_lines(keys) + MODULE_OPENING_LINES + constant_lines(codes)
    lines += TABLE_OPENING_LINES + choice_lines(codes) + TABLE_CLOSING_LINES
    return "\n".join(lines)


def render_index():
    """The resource file that gives every table its id."""
    lines = ["<!-- GENERATED by scripts/generate_strings.py. DO NOT EDIT. -->", "<resources>"]
    for code in language_codes():
        lines.append('    <jsonData id="%s" filename="%s.json"/>' % (resource_id(code), code))
    return "\n".join(lines + ["</resources>", ""])


def render_table(tables, code):
    return json.dumps(translated_entries(tables, code), ensure_ascii=False, indent=0) + "\n"


def outputs(tables):
    """Every generated file as {path from the repository root: content}."""
    files = {OUTPUT_PATH: render_module(list(tables[BASE_CODE])), INDEX_PATH: render_index()}
    for code in language_codes():
        files[os.path.join(TEXTS_FOLDER, code + ".json")] = render_table(tables, code)
    return files


def read_tables():
    return {code: read_strings(folder) for code, folder in LANGUAGES}


def write_output(path, text):
    full_path = os.path.join(REPO_ROOT, path)
    os.makedirs(os.path.dirname(full_path), exist_ok=True)
    with open(full_path, "w", encoding="utf-8") as handle:
        handle.write(text)


def main():
    tables = read_tables()
    for path, text in outputs(tables).items():
        write_output(path, text)
    print("Generated %s and %s: %d languages, %d keys each"
          % (OUTPUT_PATH, TEXTS_FOLDER, len(LANGUAGES), len(tables[BASE_CODE])))


if __name__ == "__main__":
    main()
